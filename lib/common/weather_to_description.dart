String weatherToDescription(int code) {
  // 맑음 (0)
  if (code == 0) {
    return "하루 종일 맑은 날씨예요";
  }

  // 구름 조금 (1–3)
  if (code >= 1 && code <= 3) {
    return "구름이 조금 있지만 맑아요";
  }

  // 연무/황사·먼지 (4–9)
  if (code >= 4 && code <= 9) {
    return "연무가 낀 탁한 날씨예요";
  }

  // 안개 (10–12, 40–49)
  if ((code >= 10 && code <= 12) || (code >= 40 && code <= 49)) {
    return "안개가 짙어서 시야가 나빠요";
  }

  // 번개 (13, 17, 29, 95–99)
  if (code == 13 || code == 17 || code == 29 || (code >= 95 && code <= 99)) {
    return "천둥과 번개가 치는 날씨예요";
  }

  // 비 관측 (14–16, 20–24)
  if ((code >= 14 && code <= 16) || (code >= 20 && code <= 24)) {
    return "비가 내려 우산을 챙기세요";
  }

  // 이슬비 (51–55)
  if (code >= 51 && code <= 55) {
    return "이슬비가 내려 우산이 필요해요";
  }

  // 어는 이슬비 (56–57)
  if (code >= 56 && code <= 57) {
    return "이슬비가 내려 우산이 필요해요";
  }

  // 비 (61–65)
  if (code >= 61 && code <= 65) {
    return "비가 내려 우산을 챙기세요";
  }

  // 폭우 (66–67)
  if (code == 66 || code == 67) {
    return "비가 매우 강하게 내립니다";
  }

  // 진눈깨비 (68–69)
  if (code == 68 || code == 69) {
    return "진눈깨비가 내려 체감온도 낮아요";
  }

  // 눈 (70–75)
  if (code >= 70 && code <= 75) {
    return "눈이 내려 길이 미끄러워요";
  }

  // 폭설 (85–86)
  if (code == 85 || code == 86) {
    return "눈이 많이 내려 이동이 불편해요";
  }

  // 싸락눈/우박 (77, 87–90)
  if (code == 77 || (code >= 87 && code <= 90)) {
    return "싸락눈이 내려 외출 시 주의하세요";
  }

  // 소나기 (80–82)
  if (code >= 80 && code <= 82) {
    return "짧은 소나기가 내릴 수 있어요";
  }

  // 눈보라 (36–39)
  if (code >= 36 && code <= 39) {
    return "눈보라로 시야 확보가 어려워요";
  }

  // 기본값 (혹시 미정의된 코드)
  return "변덕스러운 날씨가 예상돼요";
}
